public class Array_of_object{
    public static void main(String[]args){
        int nums[] = new int[9];
         nums[0] = 5;
         nums[1] = 4;
         nums[2] = 7;
         nums[3] = 6;
         nums[4] = 2;
         nums[5] = 3;

        for(int i=0;i<nums.length;i++){
            System.out.println(nums[i]);
        }
    }
}